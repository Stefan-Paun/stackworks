//! Code generator: checks names and arities and emits commented Stapelwerk assembly
//! (strategy and stack frame in `docs/SETZWERK.md`).

use crate::ast::{BinOp, Expr, Function, Program, Stmt, UnOp};
use crate::{Error, Pos};
use stapelwerk_core::consts::is_reserved_name;
use std::fmt::Write;

/// Maximum number of local slots (parameters 1–4 and `var`s) per function.
pub const MAX_SLOTS: u32 = 4000;
/// Maximum number of parameters per function.
pub const MAX_PARAMS: usize = 64;

/// Where a variable lives.
#[derive(Clone, Debug)]
enum Loc {
    /// `[fp - 4·k]`, k ≥ 1.
    Slot(u32),
    /// Stack argument k (0-based, i.e. parameter 5 + k) at `[fp + 8 + 4·k]`.
    StackArg(u32),
    /// Global label.
    Global(String),
}

impl Loc {
    fn operand(&self) -> String {
        match self {
            Loc::Slot(k) => format!("[fp - {}]", 4 * k),
            Loc::StackArg(k) => format!("[fp + {}]", 8 + 4 * k),
            Loc::Global(name) => format!("[{name}]"),
        }
    }
}

struct Gen<'a> {
    prog: &'a Program,
    lines: Vec<&'a str>,
    out: String,
    label: u32,
    // Per function:
    scopes: Vec<Vec<(String, Loc)>>,
    slots: u32,
    loops: Vec<(String, String)>,
}

/// Generates the assembly for a parsed program.
pub fn generate(prog: &Program, src: &str, name: &str) -> Result<String, Error> {
    check_top_level(prog)?;
    let mut g = Gen {
        prog,
        lines: src.lines().collect(),
        out: String::new(),
        label: 0,
        scopes: Vec::new(),
        slots: 0,
        loops: Vec::new(),
    };
    let name: String = name
        .chars()
        .map(|c| if c.is_control() { '?' } else { c })
        .collect();
    let _ = writeln!(g.out, "; Generated by the Setzwerk compiler from {name}.");
    let _ = writeln!(
        g.out,
        "; Expressions are evaluated into r0; r1 holds a right operand; fp/sp form the frame."
    );
    if prog.function("main").is_some() {
        g.out.push_str("\n; Program start: call main, then stop.\n");
        g.ins("call main");
        g.ins("halt");
    } else {
        g.out
            .push_str("\n; No main: this is a library of functions (for function tests).\n");
    }
    for f in &prog.functions {
        g.function(f)?;
    }
    if !prog.globals.is_empty() {
        g.out.push_str("\n; Global variables\n        .data\n");
        for gl in &prog.globals {
            let _ = writeln!(g.out, "{}: .word {}", gl.name, gl.init);
        }
    }
    Ok(g.out)
}

fn check_label_name(name: &str, pos: Pos, what: &str) -> Result<(), Error> {
    if is_reserved_name(name) {
        return Err(Error::new(
            pos,
            format!(
                "the {what} name '{name}' is reserved in the assembler (register, mnemonic, system call or constant); choose another name"
            ),
        ));
    }
    Ok(())
}

fn check_top_level(prog: &Program) -> Result<(), Error> {
    let mut seen: Vec<&str> = Vec::new();
    for g in &prog.globals {
        check_label_name(&g.name, g.pos, "variable")?;
        if seen.contains(&g.name.as_str()) {
            return Err(Error::new(g.pos, format!("'{}' is defined twice", g.name)));
        }
        seen.push(&g.name);
    }
    for f in &prog.functions {
        check_label_name(&f.name, f.pos, "function")?;
        if seen.contains(&f.name.as_str()) {
            return Err(Error::new(f.pos, format!("'{}' is defined twice", f.name)));
        }
        seen.push(&f.name);
        if f.name == "main" && !f.params.is_empty() {
            return Err(Error::new(f.pos, "main takes no parameters".to_string()));
        }
        if f.params.len() > MAX_PARAMS {
            return Err(Error::new(
                f.pos,
                format!("more than {MAX_PARAMS} parameters"),
            ));
        }
        for (i, p) in f.params.iter().enumerate() {
            if f.params[..i].contains(p) {
                return Err(Error::new(f.pos, format!("parameter '{p}' appears twice")));
            }
        }
    }
    Ok(())
}

/// Assembler mnemonic for an arithmetic or bitwise operator.
fn alu_mnemonic(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "add",
        BinOp::Sub => "sub",
        BinOp::Mul => "mul",
        BinOp::Div => "div",
        BinOp::Rem => "rem",
        BinOp::Shl => "shl",
        BinOp::Shr => "sar",
        BinOp::And => "and",
        BinOp::Xor => "xor",
        BinOp::Or => "or",
        _ => "cmp",
    }
}

/// Jump that is taken when the comparison holds (after `cmp left, right`).
fn jump_if(op: BinOp) -> &'static str {
    match op {
        BinOp::Lt => "jlt",
        BinOp::Le => "jle",
        BinOp::Gt => "jgt",
        BinOp::Ge => "jge",
        BinOp::Eq => "jz",
        _ => "jnz",
    }
}

/// Jump that is taken when the comparison does not hold.
fn jump_unless(op: BinOp) -> &'static str {
    match op {
        BinOp::Lt => "jge",
        BinOp::Le => "jgt",
        BinOp::Gt => "jle",
        BinOp::Ge => "jlt",
        BinOp::Eq => "jnz",
        _ => "jz",
    }
}

/// The immediate operand for `op r0, r0, imm`, if the literal fits the instruction.
fn immediate(op: BinOp, v: i32) -> Option<String> {
    let s16 = (-32768..=32767).contains(&v);
    match op {
        BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div | BinOp::Rem if s16 => {
            Some(v.to_string())
        }
        _ if op.is_comparison() && s16 => Some(v.to_string()),
        BinOp::And | BinOp::Or | BinOp::Xor if (0..=65535).contains(&v) => Some(v.to_string()),
        BinOp::Shl | BinOp::Shr => Some((v & 31).to_string()),
        _ => None,
    }
}

impl Gen<'_> {
    fn ins(&mut self, s: &str) {
        let _ = writeln!(self.out, "        {s}");
    }

    fn put_label(&mut self, l: &str) {
        let _ = writeln!(self.out, "{l}:");
    }

    fn new_label(&mut self, what: &str) -> String {
        self.label += 1;
        format!(".{what}{}", self.label)
    }

    fn comment_line(&mut self, pos: Pos) {
        let text = self
            .lines
            .get(pos.line.saturating_sub(1) as usize)
            .map(|l| l.trim())
            .unwrap_or("")
            .chars()
            .map(|c| if c.is_control() { ' ' } else { c })
            .collect::<String>();
        let _ = writeln!(self.out, "        ; line {}: {text}", pos.line);
    }

    fn lookup(&self, name: &str) -> Option<Loc> {
        for scope in self.scopes.iter().rev() {
            if let Some((_, loc)) = scope.iter().rev().find(|(n, _)| n == name) {
                return Some(loc.clone());
            }
        }
        self.prog
            .globals
            .iter()
            .find(|g| g.name == name)
            .map(|g| Loc::Global(g.name.clone()))
    }

    fn resolve(&self, name: &str, pos: Pos) -> Result<Loc, Error> {
        match self.lookup(name) {
            Some(l) => Ok(l),
            None if self.prog.function(name).is_some() => Err(Error::new(
                pos,
                format!("'{name}' is a function, not a variable"),
            )),
            None => Err(Error::new(
                pos,
                format!("unknown variable '{name}' (declare it with var)"),
            )),
        }
    }

    fn new_slot(&mut self, pos: Pos) -> Result<u32, Error> {
        if self.slots >= MAX_SLOTS {
            return Err(Error::new(
                pos,
                format!("more than {MAX_SLOTS} local variables in one function"),
            ));
        }
        self.slots += 1;
        Ok(self.slots)
    }

    fn function(&mut self, f: &Function) -> Result<(), Error> {
        self.scopes = vec![Vec::new()];
        self.slots = 0;
        self.loops.clear();
        let mut stores = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            let loc = if i < 4 {
                let k = self.new_slot(f.pos)?;
                stores.push(format!(
                    "st r{i}, [fp - {}]          ; parameter {p}",
                    4 * k
                ));
                Loc::Slot(k)
            } else {
                Loc::StackArg(i as u32 - 4)
            };
            self.scopes[0].push((p.clone(), loc));
        }
        // Generate the body first: the prologue needs the final number of slots.
        let outer = std::mem::take(&mut self.out);
        self.block(&f.body)?;
        let body = std::mem::replace(&mut self.out, outer);

        let _ = writeln!(self.out, "\n; fn {}({})", f.name, f.params.join(", "));
        for (i, p) in f.params.iter().enumerate().skip(4) {
            let _ = writeln!(
                self.out,
                ";   {p} is stack argument at [fp + {}]",
                8 + 4 * (i - 4)
            );
        }
        self.put_label(&f.name);
        self.ins("push fp                 ; prologue");
        self.ins("mov fp, sp");
        if self.slots > 0 {
            let _ = writeln!(
                self.out,
                "        sub sp, sp, {}           ; {} local slot(s)",
                4 * self.slots,
                self.slots
            );
        }
        for s in stores {
            self.ins(&s);
        }
        self.out.push_str(&body);
        self.ins("mov r0, 0               ; end of the function: return 0");
        self.put_label(".exit");
        self.ins("mov sp, fp              ; epilogue");
        self.ins("pop fp");
        self.ins("ret");
        Ok(())
    }

    fn block(&mut self, stmts: &[Stmt]) -> Result<(), Error> {
        self.scopes.push(Vec::new());
        for s in stmts {
            self.stmt(s)?;
        }
        self.scopes.pop();
        Ok(())
    }

    fn stmt(&mut self, s: &Stmt) -> Result<(), Error> {
        match s {
            Stmt::Var(name, init, pos) => {
                self.comment_line(*pos);
                let in_scope = self
                    .scopes
                    .last()
                    .is_some_and(|sc| sc.iter().any(|(n, _)| n == name));
                if in_scope {
                    return Err(Error::new(
                        *pos,
                        format!("'{name}' is already declared in this block"),
                    ));
                }
                if self.prog.function(name).is_some() {
                    return Err(Error::new(
                        *pos,
                        format!("'{name}' is already a function name"),
                    ));
                }
                match init {
                    Some(e) => self.expr(e)?,
                    None => self.ins("mov r0, 0"),
                }
                let k = self.new_slot(*pos)?;
                let loc = Loc::Slot(k);
                self.ins(&format!("st r0, {}          ; {name}", loc.operand()));
                if let Some(sc) = self.scopes.last_mut() {
                    sc.push((name.clone(), loc));
                }
            }
            Stmt::Assign(name, e, pos) => {
                self.comment_line(*pos);
                let loc = self.resolve(name, *pos)?;
                self.expr(e)?;
                self.ins(&format!("st r0, {}          ; {name}", loc.operand()));
            }
            Stmt::If(c, then, els, pos) => {
                self.comment_line(*pos);
                let l_else = self.new_label("if_else");
                self.cond_false(c, &l_else)?;
                self.block(then)?;
                match els {
                    None => self.put_label(&l_else),
                    Some(els) => {
                        let l_end = l_else.replace("if_else", "if_end");
                        self.ins(&format!("jmp {l_end}"));
                        self.put_label(&l_else);
                        self.block(els)?;
                        self.put_label(&l_end);
                    }
                }
            }
            Stmt::While(c, body, pos) => {
                self.comment_line(*pos);
                let top = self.new_label("while_top");
                let end = top.replace("while_top", "while_end");
                self.put_label(&top);
                self.cond_false(c, &end)?;
                self.loops.push((top.clone(), end.clone()));
                self.block(body)?;
                self.loops.pop();
                self.ins(&format!("jmp {top}"));
                self.put_label(&end);
            }
            Stmt::Break(pos) | Stmt::Continue(pos) => {
                self.comment_line(*pos);
                let Some((top, end)) = self.loops.last().cloned() else {
                    return Err(Error::new(
                        *pos,
                        "break/continue outside a loop".to_string(),
                    ));
                };
                let target = if matches!(s, Stmt::Break(_)) {
                    end
                } else {
                    top
                };
                self.ins(&format!("jmp {target}"));
            }
            Stmt::Return(e, pos) => {
                self.comment_line(*pos);
                match e {
                    Some(e) => self.expr(e)?,
                    None => self.ins("mov r0, 0"),
                }
                self.ins("jmp .exit");
            }
            Stmt::Print(e, pos) => {
                self.comment_line(*pos);
                self.expr(e)?;
                self.ins("sys WRITE_INT");
            }
            Stmt::Putc(e, pos) => {
                self.comment_line(*pos);
                self.expr(e)?;
                self.ins("sys WRITE_CHAR");
            }
            Stmt::Block(b) => self.block(b)?,
            Stmt::Expr(e, pos) => {
                self.comment_line(*pos);
                self.expr(e)?;
            }
        }
        Ok(())
    }

    /// Loads a literal or variable straight into `reg` (no other register changes).
    fn load_simple(&mut self, e: &Expr, reg: &str) -> Result<bool, Error> {
        match e {
            Expr::Int(v) => {
                if (-32768..=32767).contains(v) {
                    self.ins(&format!("mov {reg}, {v}"));
                } else {
                    self.ins(&format!("li {reg}, {v}"));
                }
                Ok(true)
            }
            Expr::Var(name, pos) => {
                let loc = self.resolve(name, *pos)?;
                self.ins(&format!("ld {reg}, {}          ; {name}", loc.operand()));
                Ok(true)
            }
            _ => Ok(false),
        }
    }

    /// Evaluates `l` into r0 and `r` into r1, or returns the immediate to use instead of r1.
    fn operands(&mut self, op: BinOp, l: &Expr, r: &Expr) -> Result<String, Error> {
        if let Expr::Int(v) = r
            && let Some(imm) = immediate(op, *v)
        {
            self.expr(l)?;
            return Ok(imm);
        }
        if matches!(r, Expr::Int(_) | Expr::Var(..)) {
            self.expr(l)?;
            self.load_simple(r, "r1")?;
            return Ok("r1".to_string());
        }
        self.expr(l)?;
        self.ins("push r0                 ; keep the left operand");
        self.expr(r)?;
        self.ins("mov r1, r0");
        self.ins("pop r0");
        Ok("r1".to_string())
    }

    /// Evaluates an expression into r0.
    fn expr(&mut self, e: &Expr) -> Result<(), Error> {
        match e {
            Expr::Int(_) | Expr::Var(..) => {
                self.load_simple(e, "r0")?;
            }
            Expr::Read => self.ins("sys READ_INT"),
            Expr::Call(name, args, pos) => self.call(name, args, *pos)?,
            Expr::Unary(op, inner) => {
                self.expr(inner)?;
                match op {
                    UnOp::Neg => self.ins("neg r0, r0"),
                    UnOp::BitNot => self.ins("not r0, r0"),
                    UnOp::Not => {
                        let l = self.new_label("not");
                        self.ins("cmp r0, 0");
                        self.ins("mov r0, 1");
                        self.ins(&format!("jz {l}"));
                        self.ins("mov r0, 0");
                        self.put_label(&l);
                    }
                }
            }
            Expr::Binary(op @ (BinOp::LogAnd | BinOp::LogOr), l, r, _) => {
                let and = *op == BinOp::LogAnd;
                let short = self.new_label(if and { "and_false" } else { "or_true" });
                let end = self.new_label(if and { "and_end" } else { "or_end" });
                let (jump, short_val, full_val) = if and { ("jz", 0, 1) } else { ("jnz", 1, 0) };
                self.expr(l)?;
                self.ins("cmp r0, 0");
                self.ins(&format!("{jump} {short}"));
                self.expr(r)?;
                self.ins("cmp r0, 0");
                self.ins(&format!("{jump} {short}"));
                self.ins(&format!("mov r0, {full_val}"));
                self.ins(&format!("jmp {end}"));
                self.put_label(&short);
                self.ins(&format!("mov r0, {short_val}"));
                self.put_label(&end);
            }
            Expr::Binary(op, l, r, _) if op.is_comparison() => {
                let rhs = self.operands(*op, l, r)?;
                let done = self.new_label("cmp");
                self.ins(&format!("cmp r0, {rhs}           ; {}", op.text()));
                self.ins("mov r0, 1               ; mov keeps the flags");
                self.ins(&format!("{} {done}", jump_if(*op)));
                self.ins("mov r0, 0");
                self.put_label(&done);
            }
            Expr::Binary(op, l, r, _) => {
                let rhs = self.operands(*op, l, r)?;
                self.ins(&format!("{} r0, r0, {rhs}", alu_mnemonic(*op)));
            }
        }
        Ok(())
    }

    /// Jumps to `target` if `c` is false (0); falls through otherwise.
    fn cond_false(&mut self, c: &Expr, target: &str) -> Result<(), Error> {
        match c {
            Expr::Binary(op, l, r, _) if op.is_comparison() => {
                let rhs = self.operands(*op, l, r)?;
                self.ins(&format!("cmp r0, {rhs}"));
                self.ins(&format!("{} {target}", jump_unless(*op)));
            }
            Expr::Binary(BinOp::LogAnd, l, r, _) => {
                self.cond_false(l, target)?;
                self.cond_false(r, target)?;
            }
            Expr::Binary(BinOp::LogOr, l, r, _) => {
                let ok = self.new_label("or_true");
                self.cond_true(l, &ok)?;
                self.cond_false(r, target)?;
                self.put_label(&ok);
            }
            Expr::Unary(UnOp::Not, inner) => self.cond_true(inner, target)?,
            _ => {
                self.expr(c)?;
                self.ins("cmp r0, 0");
                self.ins(&format!("jz {target}"));
            }
        }
        Ok(())
    }

    /// Jumps to `target` if `c` is true (not 0); falls through otherwise.
    fn cond_true(&mut self, c: &Expr, target: &str) -> Result<(), Error> {
        match c {
            Expr::Binary(op, l, r, _) if op.is_comparison() => {
                let rhs = self.operands(*op, l, r)?;
                self.ins(&format!("cmp r0, {rhs}"));
                self.ins(&format!("{} {target}", jump_if(*op)));
            }
            Expr::Binary(BinOp::LogOr, l, r, _) => {
                self.cond_true(l, target)?;
                self.cond_true(r, target)?;
            }
            Expr::Binary(BinOp::LogAnd, l, r, _) => {
                let no = self.new_label("and_false");
                self.cond_false(l, &no)?;
                self.cond_true(r, target)?;
                self.put_label(&no);
            }
            Expr::Unary(UnOp::Not, inner) => self.cond_false(inner, target)?,
            _ => {
                self.expr(c)?;
                self.ins("cmp r0, 0");
                self.ins(&format!("jnz {target}"));
            }
        }
        Ok(())
    }

    fn call(&mut self, name: &str, args: &[Expr], pos: Pos) -> Result<(), Error> {
        let Some(f) = self.prog.function(name) else {
            let msg = if self.lookup(name).is_some() {
                format!("'{name}' is a variable, not a function")
            } else {
                format!("unknown function '{name}'")
            };
            return Err(Error::new(pos, msg));
        };
        if f.params.len() != args.len() {
            return Err(Error::new(
                pos,
                format!(
                    "'{name}' takes {} argument(s), but {} are given",
                    f.params.len(),
                    args.len()
                ),
            ));
        }
        let n = args.len();
        if n == 1 {
            self.expr(&args[0])?;
        } else {
            for (i, a) in args.iter().enumerate() {
                self.expr(a)?;
                self.ins(&format!("push r0                 ; argument {}", i + 1));
            }
        }
        if (2..=4).contains(&n) {
            for i in (0..n).rev() {
                self.ins(&format!("pop r{i}"));
            }
        }
        let stack_args = n.saturating_sub(4);
        if stack_args > 0 {
            // Arguments 5… must lie in ascending order above sp: copy them, last one first.
            for i in (4..n).rev() {
                let off = 8 * (n - 1 - i);
                self.ins(&format!("ld r0, [sp + {off}]"));
                self.ins(&format!(
                    "push r0                 ; stack argument {}",
                    i + 1
                ));
            }
            for i in 0..4 {
                let off = 4 * (n - 1 - i) + 4 * stack_args;
                self.ins(&format!("ld r{i}, [sp + {off}]"));
            }
        }
        self.ins(&format!("call {name}"));
        if stack_args > 0 {
            self.ins(&format!(
                "add sp, sp, {}          ; drop the argument copies",
                4 * (n + stack_args)
            ));
        }
        Ok(())
    }
}
